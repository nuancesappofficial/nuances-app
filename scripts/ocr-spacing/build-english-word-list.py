#!/usr/bin/env python3
"""Builds englishWords.generated.ts for the OCR spacing restorer.

Expands the hunspell en_US dictionary (SCOWL-derived) with its affix rules and
writes two front-coded lists: lowercase words and lowercased proper nouns.

Usage (needs a hunspell en_US dictionary, e.g. Debian/Ubuntu
`apt install hunspell-en-us`):
  python3 scripts/ocr-spacing/build-english-word-list.py \
      /usr/share/hunspell/en_US.dic /usr/share/hunspell/en_US.aff \
      src/features/ocrSpacing/englishWords.generated.ts
Then copy the output to
  supabase/functions/ai-proxy/_shared/ocrSpacing/englishWords.generated.ts
(ocrSpacing.test.mjs fails if the two copies differ).
"""
import re
import sys
from pathlib import Path

dic_path, aff_path = sys.argv[1], sys.argv[2]
out_path = Path(sys.argv[3] if len(sys.argv) > 3 else 'src/features/ocrSpacing/englishWords.generated.ts')

aff = Path(aff_path).read_text(encoding='utf-8').splitlines()
rules = {}  # flag -> (PFX|SFX, cross_product, [(strip, add, condition)])
i = 0
while i < len(aff):
    p = aff[i].split()
    if len(p) == 4 and p[0] in ('PFX', 'SFX') and p[2] in 'YN':
        kind, flag, cross, n = p[0], p[1], p[2] == 'Y', int(p[3])
        entries = []
        for j in range(n):
            q = aff[i + 1 + j].split()
            strip = '' if q[2] == '0' else q[2]
            add = '' if q[3] == '0' else q[3].split('/')[0]
            cond = re.compile(('^' + q[4]) if kind == 'PFX' else (q[4] + '$'))
            entries.append((strip, add, cond))
        rules[flag] = (kind, cross, entries)
        i += n + 1
    else:
        i += 1

words = set()
for line in Path(dic_path).read_text(encoding='utf-8').splitlines()[1:]:
    w, _, flags = line.partition('/')
    words.add(w)
    suffixed, prefixes = [], []
    for f in flags:
        rule = rules.get(f)
        if not rule:
            continue
        kind, cross, entries = rule
        for strip, add, cond in entries:
            if kind == 'SFX':
                if cond.search(w) and w.endswith(strip):
                    nw = w[:len(w) - len(strip)] + add
                    words.add(nw)
                    if cross:
                        suffixed.append(nw)
            elif cond.search(w) and w.startswith(strip):
                words.add(add + w[len(strip):])
                if cross:
                    prefixes.append((add, strip))
    for nw in suffixed:
        for add, strip in prefixes:
            words.add(add + nw[len(strip):])

common = sorted({w for w in words if re.fullmatch(r'[a-z]+', w)})
proper = sorted({w.lower() for w in words if re.fullmatch(r'[A-Za-z]+', w)} - set(common))


def front_code(items):
    out, prev = [], ''
    for w in items:
        k = 0
        while k < min(len(prev), len(w), 35) and prev[k] == w[k]:
            k += 1
        out.append(chr(48 + k) + w[k:])
        prev = w
    return ''.join(out)


header = f'''// AUTO-GENERATED by scripts/ocr-spacing/build-english-word-list.py — do not edit by hand.
//
// English word forms expanded from the hunspell en_US dictionary, which is
// derived from SCOWL (Spell Checker Oriented Word Lists):
//   - ENGLISH_WORDS_FRONT_CODED: {len(common)} lowercase words (usable as split pieces)
//   - ENGLISH_PROPER_NOUNS_FRONT_CODED: {len(proper)} names/places, lowercased (never
//     split, never used as pieces)
//
// SCOWL: Copyright 2000-2011 by Kevin Atkinson. Permission to use, copy,
// modify, distribute and sell these word lists, the associated scripts, the
// output created from the scripts, and its documentation for any purpose is
// hereby granted without fee, provided that the above copyright notice appears
// in all copies and that both that copyright notice and this permission notice
// appear in supporting documentation. Kevin Atkinson makes no representations
// about the suitability of this array for any purpose. It is provided "as is"
// without express or implied warranty.
//
// Encoding: sorted words, front-coded with no separators. Each entry starts
// with one marker character (code 48 + n, never a lowercase letter) meaning
// "reuse the first n letters of the previous word", followed by the remaining
// lowercase letters.

'''
out_path.write_text(
    header
    + f"export const ENGLISH_WORDS_FRONT_CODED =\n  '{front_code(common)}';\n\n"
    + f"export const ENGLISH_PROPER_NOUNS_FRONT_CODED =\n  '{front_code(proper)}';\n",
    encoding='utf-8',
)
print(f'{out_path}: {len(common)} words, {len(proper)} proper nouns')
